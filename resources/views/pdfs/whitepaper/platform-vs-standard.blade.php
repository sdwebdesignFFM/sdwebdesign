<h2>5. Eigene Plattform: wann sie sich rechnet</h2>
<p>Die eigene Plattform ist die teuerste, langsamste, aber strategisch oft die beste Lösung. Sie rechnet sich, wenn folgende Faktoren zusammenkommen:</p>

<h3>Pflicht-Voraussetzungen</h3>
<ol>
    <li>Die Workflows, die digitalisiert werden sollen, sind <strong>kein Standard</strong> — sondern ein echter Wettbewerbsvorteil oder eine harte branchenspezifische Anforderung.</li>
    <li>Die Plattform wird von <strong>mehr als einer Hand voll Personen</strong> regelmäßig genutzt (oder mehreren externen Stakeholder-Gruppen).</li>
    <li>Es gibt jemanden im Unternehmen, der als <strong>Auftraggeber/Sponsor</strong> über mindestens 12 Monate verfügbar ist.</li>
    <li>Das Budget liegt im fünfstelligen Bereich aufwärts (typisch 50–250 k EUR im ersten Jahr, je nach Scope).</li>
</ol>

<h3>Typische Use-Cases im Mittelstand</h3>
<ul>
    <li><strong>Workforce-Management mit Disposition:</strong> Personalvermittler, Reinigungsdienste, Sicherheitsdienste, Handwerksbetriebe mit Teams im Außeneinsatz.</li>
    <li><strong>Kunden- &amp; Partnerportale mit Geschäftslogik:</strong> Statusabfragen, Angebote, Self-Service, individuelle Preise.</li>
    <li><strong>Interne Tools, die Standard-Software ergänzen:</strong> die letzten 20 % Branchen-Spezifika, die DATEV/SAP/Personio nicht abdecken.</li>
    <li><strong>Branchen-Spezialprozesse:</strong> Schulungs-Verwaltung mit Zertifikat-Tracking, Compliance-Workflows, Hybrid-B2B/B2C-Modelle.</li>
</ul>

<h3>Warum Mittelstand-Plattformen häufig anders gebaut werden müssen als Konzern-Plattformen</h3>
<p>Konzerne haben oft ganze IT-Abteilungen und können sich Microservice-Architekturen, eigene Plattform-Teams und mehrjährige Roll-out-Pläne leisten. Im Mittelstand ist das selten realistisch. Was funktioniert: ein <strong>monolithisches, klar strukturiertes System</strong>, mit moderner Technik (Laravel/Symfony, modernes Frontend), das von einem kleinen Team über Jahre gewartet werden kann. Begleitung über Monate und Jahre statt einzelner Projekt-Sprints.</p>

{{-- 6 --}}
<h2>6. Entscheidungs-Framework in vier Fragen</h2>
<p>Bevor Sie das erste Angebot anfragen — beantworten Sie diese vier Fragen schriftlich. Sie sind die Grundlage jeder belastbaren Discovery.</p>

<h3>Frage 1 — Wie viele Personen werden die Lösung regelmäßig nutzen?</h3>
<ul>
    <li>1–5 Personen: meist DIY, AI-Builder oder Standard-Software.</li>
    <li>5–50 Personen: Standard-Software prüfen. Wenn Workflows nicht passen → eigene Plattform.</li>
    <li>50+ Personen: praktisch immer eigene Plattform oder Branchen-Suite.</li>
</ul>

<h3>Frage 2 — Wie spezifisch sind die Workflows?</h3>
<ul>
    <li>Standard-Workflows einer Branche → Standard-Software.</li>
    <li>Mischformen, die sich noch entwickeln → DIY-Validation, dann eigene Plattform.</li>
    <li>Echter Wettbewerbsvorteil im Workflow → eigene Plattform.</li>
</ul>

<h3>Frage 3 — Wie groß ist die Datenmenge und wie schnell wächst sie?</h3>
<ul>
    <li>Bis 10.000 Datensätze, langsamer Wachstum: DIY-Tools möglich.</li>
    <li>Mehrere zehntausend Datensätze, regelmäßiger Schreibverkehr: Standard oder eigene Plattform.</li>
    <li>Hunderttausende Datensätze, hohe Lese-Frequenz: eigene Plattform mit Datenbank-Architektur.</li>
</ul>

<h3>Frage 4 — Welche Compliance-Anforderungen bestehen?</h3>
<ul>
    <li>DSGVO &amp; AVV ausreichend, keine Branchen-Specifics: Standard oder DIY mit DPA.</li>
    <li>Branchen-Compliance (z. B. Automotive CRA, Pharma-GxP, Bank-BAIT): eigene Plattform mit klarer Architektur und Audit-Trail.</li>
    <li>Datenhoheit (Standort EU/DE) gefordert: prüfen, ob Standard-/DIY-Anbieter das abdecken — sonst eigene Plattform.</li>
</ul>
