<h2>1. Warum die Frage zu spät gestellt wird</h2>
<p>In den meisten Mittelstandsbetrieben entsteht der Bedarf an einer eigenen Plattform nicht aus einer Strategie heraus, sondern aus einer Reihe von Workarounds. Excel-Tabellen, die zwischen Vertrieb und Disposition hin- und hergeschickt werden. Eine Standardsoftware, die zu 80 % passt — aber die letzten 20 % sind genau die Workflows, in denen das Geschäft tatsächlich läuft. Ein selbstgebautes Access-Tool aus 2014, das nur noch eine Person bedienen kann.</p>
<p>Wenn die Frage „bauen wir das eigentlich selbst, oder kaufen wir eine Lösung?" gestellt wird, ist die Schmerzgrenze meist schon überschritten. Die Konsequenz: die Entscheidung wird unter Druck getroffen. Mehrere Anbieter werden parallel angefragt, drei Angebote landen auf dem Tisch — und es gibt keine gemeinsame Grundlage, sie zu vergleichen, weil jeder Anbieter den Bedarf anders interpretiert.</p>
<div class="callout">
    <p><strong>Kernthese:</strong> Die wichtigste Investition vor jeder Plattform-Entscheidung ist nicht die Auswahl des Anbieters, sondern die <em>Klärung der Anforderungen</em>. Ein dokumentiertes Discovery-Ergebnis macht jeden weiteren Schritt 10× günstiger und 3× schneller.</p>
</div>

{{-- 2 --}}
<h2>2. Drei Schichten der Software-Entscheidung</h2>
<p>Software-Entscheidungen für den Mittelstand laufen auf drei sehr unterschiedlichen Schichten ab. Die meisten Fehlentscheidungen entstehen, weil eine Schicht mit den Mitteln einer anderen gelöst wird.</p>

<h3>Schicht 1 — Standard-Werkzeuge</h3>
<p>Werkzeuge, die ein klar abgegrenztes Problem branchenneutral lösen: Buchhaltung, Lohn, CRM, E-Mail, Office. Hier ist Standard-Software (DATEV, Personio, HubSpot, Microsoft 365) immer richtig. Eigenentwicklung wäre Verschwendung.</p>

<h3>Schicht 2 — Branchenspezifische Suiten</h3>
<p>Lösungen, die für eine ganze Branche gebaut sind: Werkstattsoftware, Zahnarzt-Praxismanagement, Lager-Wirtschaftssysteme. Wenn die Branche eng definiert und die eigenen Prozesse nicht extrem speziell sind, passt Standard-Software meist gut. Wenn aber das Geschäft in einer Nische operiert (z. B. Personalvermittlung Automotive mit CarPool-Logistik) oder in einer Übergangsphase (Hybrid-Modell mit B2C+B2B), reichen die Suiten nicht mehr.</p>

<h3>Schicht 3 — Operative Workflows</h3>
<p>Die Schicht, auf der das Geschäft tatsächlich läuft: Disposition, Auftragsabwicklung, Schulung, Zertifikate, Stunden, Abrechnung, Reporting. Genau hier scheitern Standard-Werkzeuge regelmäßig — weil die operativen Workflows mittelständisch eigen sind und sich über Jahre weiterentwickeln. Hier entsteht der Bedarf für eigene Plattformen.</p>

<div class="callout">
    <p><strong>Faustregel:</strong> Schicht 1 immer Standard. Schicht 2 prüfen. Schicht 3 individuell — sofern die Workflows den Wettbewerbsvorteil bilden.</p>
</div>
<div class="pagebreak"></div>

