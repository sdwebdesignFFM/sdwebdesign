<h2>4. DIY- &amp; AI-Builder: wann sie tragen — und wann nicht</h2>
<p>Lovable, Bubble, Webflow, Zapier, Make, Retool, Glide: die DIY-Welt ist 2024–2026 dramatisch besser geworden. Für viele Anwendungsfälle sind sie heute eine ernsthafte Alternative zur Eigenentwicklung. Aber sie haben klare Grenzen, die im Mittelstand schnell relevant werden.</p>

<h3>Wann DIY-/AI-Builder gut tragen</h3>
<ul>
    <li>Internes Tool für ein kleines Team (≤ 20 Nutzer), kein kritischer externer Kunden-Kontakt.</li>
    <li>Ein klar abgegrenzter Workflow ohne komplexe Geschäftslogik (z. B. ein Bewerbungsformular, ein simples Buchungs-Tool).</li>
    <li>Schneller Prototyp, um eine Hypothese zu testen, bevor in Eigenentwicklung investiert wird.</li>
    <li>Datenmenge im niedrigen Bereich, keine kritischen Compliance-Anforderungen (DSGVO, Branchenstandards).</li>
</ul>

<h3>Wo DIY-/AI-Builder typisch scheitern</h3>
<ul>
    <li><strong>Domain-Komplexität:</strong> Sobald Geschäftslogik mit mehreren Status-Übergängen, Validierungen und Rollen ins Spiel kommt, wird der Builder unwartbar. Was als 2-Wochen-Lösung beginnt, wird nach 6 Monaten zur Wartungs-Falle.</li>
    <li><strong>Compliance &amp; Datenschutz:</strong> Hosted in den USA, kein DPA, keine Auftragsverarbeitung — für viele Mittelständler ein No-Go.</li>
    <li><strong>Skalierung:</strong> Performance bricht typisch ab 10.000 Datensätzen ein.</li>
    <li><strong>Vendor-Lock-In:</strong> Die Plattform stellt den Service ein oder verdoppelt die Preise — die Migration ist meist nicht trivial möglich.</li>
    <li><strong>Integration:</strong> Anbindung an bestehende Systeme (DATEV, SAP, eigene Excel-Welten) ist selten sauber lösbar.</li>
</ul>

<div class="callout">
    <p><strong>Empfehlung:</strong> DIY-/AI-Builder als <em>Validation-Tool</em> einsetzen. Wenn die Hypothese trägt und der Prozess bleibt, in Eigenentwicklung migrieren. Niemals den Prototyp zur Produktivlösung wachsen lassen, ohne den Architektur-Entscheid bewusst zu treffen.</p>
</div>
