<h2>7. Pilot statt Komplettlösung</h2>
<p>Die teuerste Plattform-Strategie ist die, bei der zuerst ein „großes Konzept" entsteht und dann ein 18-monatiges Komplett-Projekt umgesetzt wird. Erfahrungsgemäß scheitert sie regelmäßig — entweder weil sich die Anforderungen während der Bauphase ändern, oder weil das Team das große Projekt nicht durchhält.</p>
<p>Was im Mittelstand fast immer funktioniert: ein <strong>Pilot-Modul</strong>. Ein klar abgegrenztes erstes Feature, das in 4–6 Wochen live geht, Wert liefert und die Grundlage für die Architektur legt. Aus diesem Pilot wächst dann iterativ die volle Plattform — über 12–24 Monate, in für die Organisation verkraftbaren Schritten.</p>

<h3>Vorteile des Pilot-Ansatzes</h3>
<ul>
    <li>Lernkurve für alle Beteiligten (Auftraggeber, Anwender, Entwickler) ist klein und schnell.</li>
    <li>Anforderungen werden konkret, nicht abstrakt — und aus dem Anwenden korrigiert.</li>
    <li>Architektur-Entscheidungen werden auf Basis von echtem Verhalten getroffen, nicht von Annahmen.</li>
    <li>Budget bleibt steuerbar; Stop-Point ist nach jedem Modul möglich.</li>
</ul>

