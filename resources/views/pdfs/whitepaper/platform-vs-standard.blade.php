<h2>3. Standard-Software: wann sie reicht</h2>
<p>Standard-Software ist im Mittelstand fast immer der bessere Startpunkt — und in der Mehrzahl der Fälle auch der richtige Endpunkt. Sie passt, wenn folgende Bedingungen alle zutreffen:</p>
<ul>
    <li>Die Workflows in Ihrem Unternehmen unterscheiden sich nicht wesentlich von der Branche.</li>
    <li>Es gibt eine etablierte Lösung mit ausreichend Konfigurierbarkeit (Personio für HR, Shopify für B2C-Shop, SAP B1 für ERP im klassischen Mittelstand).</li>
    <li>Die Datenschnittstellen zu Ihren übrigen Systemen sind dokumentiert und nutzbar.</li>
    <li>Die laufenden Lizenzkosten stehen in einem vertretbaren Verhältnis zum Nutzen.</li>
    <li>Sie sind bereit, Ihre Prozesse an die Software anzupassen — nicht umgekehrt.</li>
</ul>
<p>Der letzte Punkt ist der entscheidende. Standard-Software erzwingt eine gewisse Vereinheitlichung. Wenn Ihr Geschäftsmodell darauf beruht, dass Ihre Workflows <em>besser</em> sind als die Ihrer Konkurrenz, dann ist diese Vereinheitlichung der Verlust eines Wettbewerbsvorteils.</p>

<h3>Typische Einsatzbereiche im Mittelstand</h3>
<table>
    <tr><th>Bereich</th><th>Empfohlene Standard-Lösung</th><th>Wann eigene Plattform sinnvoller ist</th></tr>
    <tr><td>Buchhaltung &amp; Lohn</td><td>DATEV, Lexware, Personio</td><td>Praktisch nie</td></tr>
    <tr><td>CRM</td><td>HubSpot, Pipedrive, SuperOffice</td><td>Wenn Lead-Workflows sehr branchenspezifisch sind</td></tr>
    <tr><td>E-Commerce B2C</td><td>Shopify, WooCommerce</td><td>Bei B2B-Logik mit komplexen Preismodellen</td></tr>
    <tr><td>ERP/Warenwirtschaft</td><td>SAP B1, Microsoft Dynamics, Sage</td><td>Bei sehr eigenen Produktionsprozessen</td></tr>
    <tr><td>Disposition &amp; Workforce</td><td>Sehr branchenspezifisch</td><td>Häufig — siehe Abschnitt 5</td></tr>
</table>

