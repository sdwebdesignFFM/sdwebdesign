<h2>8. Risiken und Mitigation</h2>
<table>
    <tr><th>Risiko</th><th>Mitigation</th></tr>
    <tr>
        <td>Anbieter-Insolvenz / Personal-Wechsel beim Anbieter</td>
        <td>Code-Eigentum vertraglich klären; Quellcode bei Auftraggeber. Mindestens zwei Personen kennen das System.</td>
    </tr>
    <tr>
        <td>Über-Engineering — die Plattform kann „alles", aber niemand nutzt mehr als 30 %</td>
        <td>Pilot-Ansatz; jede Funktion erst dann bauen, wenn der konkrete Bedarf belegt ist.</td>
    </tr>
    <tr>
        <td>Mangelnde interne Kapazität für die Begleitung</td>
        <td>Eingebetteter Product Owner vom Anbieter, der die Brücke zum Geschäft baut. Ein bis zwei Personen aus der Organisation als Fachverantwortliche.</td>
    </tr>
    <tr>
        <td>Compliance-Lücke entsteht erst spät</td>
        <td>Compliance-Anforderungen in der Discovery-Phase explizit machen, nicht in Phase 5.</td>
    </tr>
    <tr>
        <td>Tech-Stack veraltet schnell</td>
        <td>Mainstream-Stacks (PHP/Laravel, TypeScript, Python) bevorzugen. Vorsicht bei Nischen-Frameworks.</td>
    </tr>
</table>

