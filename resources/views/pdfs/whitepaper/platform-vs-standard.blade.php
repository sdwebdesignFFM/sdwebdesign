<h2>9. Roadmap-Schablone für die ersten 12 Monate</h2>

<h4>Monat 0 — Discovery (1–4 Wochen)</h4>
<p>Anforderungen aufnehmen, Stakeholder mappen, Tech-Optionen prüfen, Risiken benennen, Discovery-Dokument erstellen.</p>

<h4>Monat 1–2 — Pilot-Modul (4–6 Wochen)</h4>
<p>Erstes klar abgegrenztes Feature. Eingerichtete Entwicklungsumgebung, Datenmodell-Grundlage, ein Workflow live.</p>

<h4>Monat 3–4 — Erweiterung (6–8 Wochen)</h4>
<p>Zweites und drittes Modul auf Basis erster Anwender-Erfahrungen. Stabilisierung und Bug-Fixing parallel.</p>

<h4>Monat 5–8 — Ausbau-Phase (12–16 Wochen)</h4>
<p>Vollständiger Funktionsumfang nach Discovery-Roadmap. Schnittstellen zu bestehenden Systemen. Dokumentation und Schulung.</p>

<h4>Monat 9–12 — Konsolidierung &amp; nächste Welle</h4>
<p>Stabiler Betrieb. Erste Lernzyklen aus den realen Anwendungen. Roadmap für Jahr 2 auf Basis dessen, was wirklich gebraucht wird.</p>

